function generateProfileNumber(existing) {
  let n;
  do {
    n = Math.floor(Math.random() * 9000000) + 1000000;
  } while (existing.has(n));
  existing.add(n);
  return n;
}

function generateSlug(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60) || "supplier";
}

